
-- Create the OKR data table
CREATE TABLE IF NOT EXISTS public.okr_data (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  name TEXT,
  nodes JSONB NOT NULL,
  edges JSONB NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Add RLS policies to secure the table
ALTER TABLE public.okr_data ENABLE ROW LEVEL SECURITY;

-- Policy to allow users to see only their own data
CREATE POLICY "Users can view their own OKR data" ON public.okr_data
  FOR SELECT USING (auth.uid() = user_id);

-- Policy to allow users to insert their own data
CREATE POLICY "Users can insert their own OKR data" ON public.okr_data
  FOR INSERT WITH CHECK (auth.uid() = user_id);

-- Policy to allow users to update their own data
CREATE POLICY "Users can update their own OKR data" ON public.okr_data
  FOR UPDATE USING (auth.uid() = user_id);

-- Policy to allow users to delete their own data
CREATE POLICY "Users can delete their own OKR data" ON public.okr_data
  FOR DELETE USING (auth.uid() = user_id);

-- Add indexes for performance
CREATE INDEX IF NOT EXISTS okr_data_user_id_idx ON public.okr_data (user_id);
